"""Alembic environment. URL comes from app settings, never from alembic.ini."""

from __future__ import annotations

from logging.config import fileConfig
from typing import Any

from alembic import context
from alembic.operations import ops
from sqlalchemy import Connection

import app.infrastructure.database.models  # noqa: F401  (registers tables)
from app.core.config import get_settings
from app.infrastructure.database.base import Base
from app.infrastructure.database.session import build_engine

config = context.config
if config.config_file_name is not None and config.attributes.get("configure_logger", True):
    fileConfig(config.config_file_name, disable_existing_loggers=False)

target_metadata = Base.metadata


def _url() -> str:
    # Tests pass an explicit URL; otherwise use DATABASE_URL from settings.
    override = config.attributes.get("database_url")
    if override:
        return str(override)
    return get_settings().database_url.get_secret_value()


# Explicit on every new table: shared hosts may default to latin1 / MyISAM (ADR-0002).
MYSQL_TABLE_OPTIONS = {
    "mysql_engine": "InnoDB",
    "mysql_charset": "utf8mb4",
    "mysql_collate": "utf8mb4_unicode_ci",
}


def _dropped_tables(container: ops.OpContainer) -> set[str]:
    names: set[str] = set()
    for op in container.ops:
        if isinstance(op, ops.DropTableOp):
            names.add(op.table_name)
        elif isinstance(op, ops.OpContainer):
            names |= _dropped_tables(op)
    return names


def _polish(container: ops.OpContainer, dropped_tables: set[str] | None = None) -> None:
    """Adjust autogenerated operations for portability.

    - CREATE TABLE gets InnoDB/utf8mb4 options.
    - DROP INDEX on a table that is dropped anyway is removed: dropping the table
      drops its indexes, and MySQL refuses to drop an index a FK still uses.
    """
    if dropped_tables is None:
        dropped_tables = _dropped_tables(container)
    kept: list[ops.MigrateOperation] = []
    for op in container.ops:
        if isinstance(op, ops.OpContainer):
            _polish(op, dropped_tables)
            if not op.ops:
                continue
        if isinstance(op, ops.CreateTableOp):
            for key, value in MYSQL_TABLE_OPTIONS.items():
                op.kw.setdefault(key, value)
        if isinstance(op, ops.DropIndexOp) and op.table_name in dropped_tables:
            continue
        kept.append(op)
    container.ops[:] = kept


def _process_revision_directives(_context: Any, _revision: Any, directives: list[Any]) -> None:
    for script in directives:
        _polish(script.upgrade_ops)
        _polish(script.downgrade_ops)


def _configure(connection: Connection) -> None:
    context.configure(
        connection=connection,
        target_metadata=target_metadata,
        render_as_batch=connection.dialect.name == "sqlite",
        compare_type=True,
        process_revision_directives=_process_revision_directives,
    )


def run_migrations_offline() -> None:
    context.configure(
        url=_url(),
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
    )
    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online() -> None:
    connection = config.attributes.get("connection")
    if connection is not None:
        _configure(connection)
        with context.begin_transaction():
            context.run_migrations()
        return
    engine = build_engine(_url())
    try:
        with engine.connect() as conn:
            _configure(conn)
            with context.begin_transaction():
                context.run_migrations()
    finally:
        engine.dispose()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
